<h3>مثال عملی دقیق:</h3><p>می‌خواهی به ده مشتری که بیش از شصت روز نیامده‌اند و احتمال ریزش بالای هفتاد درصد دارند، پیام بازگشت بدهی: فیلتر سطح خطر بالا → جستجو خالی → تیک همه ده نفر → دکمه ارسال پیام گروهی → متن پیام را بنویس مثل «سلام احمد عزیز، دلتنگت شدیم — پانزده درصد تخفیف بازگشت با کد BAZGASHT15 فقط تا جمعه» → انتخاب کانال پیامک → تیک افزودن نام خودکار → ارسال → هر پیام با نام خود مشتری می‌رود و در تاریخچه پیام‌ها و فعالیت‌ها ثبت می‌شود</p>
<ul class="checklist"><li><i>☐</i> ده مشتری با خطر بالا تیک زده و پیام گروهی آزمایشی ارسال شد</li></ul>
</div>

<div class="card" id="m11"><h2>۱۱. درآمد بازگشتی ماهانه یکتا — بدون تکرار — چطور آمار متفاوت را بررسی کنیم</h2>
<p>مسیر: <span class="kbd">گزارش‌ها → درآمد بازگشتی</span> — <span class="kbd">/app/reports?tab=recovery</span></p>
<picture><source srcset="/img/real-recovery-1404.webp" type="image/webp"><img src="/img/real-recovery-1404.jpg" alt="درآمد بازگشتی یکتا"></picture>
<h3>صفحه چه دارد:</h3><ul>
<li>شش کارت بالا: بازگشت سی روزه با تعداد و نرخ بازگشت درصد، درآمد بازگشتی سی روزه با تومان، بازگشت هفت روزه، کل بازگشت دوازده ماهه با تومان، میانگین ماهانه بازگشت با تومان، در معرض خطر فعلی با تعداد</li>
<li>سمت چپ: نمودار میله‌ای با دو محور تومان و تعداد — هر میله یک ماه شمسی یکتا مثل تیر همراه سال، مرداد همراه سال، شهریور همراه سال، مهر همراه سال — بدون تکرار</li>
<li>سمت راست: جدول ماهانه با ستون‌های ماه شمسی یکتا، تعداد بازگشت، درآمد بازگشتی</li>
<li>پایین: جدول بازگشت‌های بازه انتخابی با نام و موبایل و غیبت روز و مبلغ بازگشت و تاریخ شمسی و دکمه پرونده</li>
<li>پایین‌تر: پنج بازگشت برتر با امتیاز دو برابر</li>
</ul>
<h3>مثال:</h3><p>می‌خواهی ببینی شهریور چند نفر برگشته‌اند و چقدر سود داده‌اند: برو تب درآمد بازگشتی → جدول ماهانه → ردیف شهریور همراه سال → ستون تعداد ۳۶ نفر و درآمد ۱،۱۰۰،۰۰۰ تومان و نرخ ۹ درصد — روی ردیف کلیک کن تا فهرست همان سی و شش نفر در بازه انتخابی را در جدول پایین ببینی — روی پرونده هر کدام کلیک کن تا پروفایل سیصد و شصت درجه‌شان باز شود</p>
</div>

<div class="card" id="m12"><h2>۱۲. آرشیو گزارش هفتگی خودکار — تاریخچه کامل با گراف داخل ایمیل — چطور تاریخچه را ببینیم</h2>
<p>مسیر: <span class="kbd">مشتریان و فروش → آرشیو گزارش‌های بازگشت</span> — <span class="kbd">/app/reports/recovery/history</span></p>
<h3>صفحه آرشیو چه دارد:</h3><ul>
<li>شش کارت بالا: کل گزارش‌های آرشیو، مجموع بازگشت، کل درآمد بازگشتی، میانگین نرخ بازگشت، گزارش‌های سی روز اخیر، رکورد درآمد یک هفته</li>
<li>نوار جستجو با تاریخ شمسی مثل ۰۵ یا بخشی از خلاصه → فیلتر بازه شمسی از تا با تقویم شمسی</li>
<li>نمودار خطی روند دوازده گزارش آخر: محور چپ تعداد نفر، محور راست تومان — هر نقطه یک گزارش هفتگی</li>
<li>جدول با صفحه‌بندی: تاریخ شمسی گزارش، بازه گزارش از تا، بازگشت هفته و درآمد هفته، بازگشت سی روزه و درآمد سی روزه، نرخ بازگشت درصد، وضعیت رنگی (فعال و پربازده، پایدار، بدون بازگشت)، ایمیل‌های ارسالی (مثلا دو مورد اول و و دو مورد دیگر)، عملیات مشاهده کامل و ارسال دوباره</li>
<li>دکمه‌ها: تولید گزارش همین الان با تایید، دانلود فایل صفحه گسترده آرشیو، رفتن به گزارش لحظه‌ای و مرکز بازگشت</li>
<li>حالت خالی: اگر آرشیو خالی باشد، کارت بزرگ با آیکون و متن هنوز گزارشی نیست و دکمه بزرگ تولید اولین گزارش همین الان</li>
</ul>
<h3>صفحه جزئیات هر گزارش:</h3><ul>
<li>خلاصه متنی، ایمیل‌های ارسالی با برچسب، چهار کارت امتیاز (بازگشت هفته با درآمد، سی روزه با درآمد، نرخ بازگشت از در خطر، کل دوازده ماهه)، دو ستون نمودار ماهانه یکتا + جدول ماهانه و جدول پنج مشتری برتر با نام و موبایل و غیبت روز و مبلغ و تاریخ شمسی + جیسون خام برای توسعه‌دهنده</li>
<li>دکمه‌ها: بازگشت به آرشیو، ارسال دوباره همین گزارش به مدیر، مرکز بازگشت، گزارش لحظه‌ای</li>
</ul>
<h3>زمان‌بندی قابل تنظیم:</h3><p>مسیر تنظیمات → اعلان‌ها → بلوک گزارش خودکار بازگشت: فعال یا غیر فعال، ساعت صبح و عصر و روزهای هفته شنبه تا جمعه تیک و ایمیل اضافی — بررسی هر ساعت با تلورانس سی دقیقه و کش بیست و پنج ساعته برای جلوگیری از دو بار ارسال</p>
</div>

<div class="card" id="m13"><h2>۱۳. داشبورد فرماندهی و ویجت درآمد بازگشتی همیشه روشن</h2>
<p>مسیر: <span class="kbd">/app</span> — پیشخوان</p>
