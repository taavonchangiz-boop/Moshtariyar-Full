<p>مسیر: <span class="kbd">مشتریان و فروش → فروش سریع</span> — <span class="kbd">/app/pos</span> — گزارش صندوق: <span class="kbd">/app/pos/cashier</span></p>
<h3>گام به گام دقیق فروش:</h3><ol>
<li><b>انتخاب انبار:</b> بالا — کشویی انبارها — گرید محصولات همان انبار می‌آید — موجودی هر محصول کنارش نوشته شده — اگر موجودی صفر باشد کارت کم‌رنگ می‌شود</li>
<li><b>جستجو و انتخاب مشتری:</b> کادر جستجوی مشتری — موبایل یا نام را بزن — فهرست بازشونده با نام و امتیاز و کیف پول می‌آید — انتخاب کن — کادر سبز «مشتری انتخاب شده» با نام و امتیاز و موجودی کیف پول و دکمه حذف می‌آید — اگر مشتری جدید است، بخش مشتری سریع پایین: نام و موبایل سریع را بزن و دکمه افزودن سریع — بدون رفتن به صفحه دیگر مشتری ساخته می‌شود و انتخاب می‌شود</li>
<li><b>هشدار حفظ مشتری:</b> اگر مشتری با ارزش است و مدت زیادی نیامده (مثلا آخرین خرید شصت و هشت روز پیش و احتمال رفتنش هفتاد و هشت درصد)، همان لحظه نوار نارنجی یا قرمز بالای سبد می‌آید — متن فارسی عامیانه: «این مشتری فلان روز پیش آخرین خرید داشته و احتمال رفتنش زیاد است — پیشنهاد پانزده درصد تخفیف برای نگهداری» — دو دکمه: «اعمال تخفیف پانزده درصد» و «رد کردن» — اگر اعمال بزنی، ردیف تخفیف خودکار پر می‌شود — اگر رد کنی، نوار بسته می‌شود</li>
<li><b>افزودن محصول به سبد:</b> از گرید محصول بزن — به سبد راست اضافه می‌شود — هر ردیف سبد: نام محصول، تعداد با + و -، قیمت واحد، جمع ردیف، حذف با ضربدر قرمز — اگر محصول ناموجود باشد هشدار می‌آید</li>
<li><b>تخفیف کلی:</b> نوع تخفیف: درصد یا مبلغ ثابت — مقدار: مثلا پانزده — اگر از هشدار اعمال کرده باشی، خودکار پر است — می‌توانی تغییر دهی</li>
<li><b>وفاداری:</b> بخش استفاده از امتیاز یا کیف پول — مثلا تیک استفاده از کیف پول و مبلغ — موجودی کیف پول کم می‌شود — اگر کیف پول کافی نباشد هشدار می‌آید</li>
<li><b>خلاصه:</b> جمع جزئی، تخفیف، مالیات نه درصد، جمع کل با عدد فارسی و تومان — مثلا جمع کل: دویست و یک هزار و ششصد و پنجاه تومان — با خط درشت</li>
<li><b>روش پرداخت:</b> تیک‌های گرد: نقدی، کارت، انتقال، نسیه — می‌توانی چند روش را تیک بزنی و مبلغ هر کدام را بنویسی — مثلا نصف نقدی نصف کارت</li>
<li><b>یادداشت فاکتور:</b> متن اختیاری که پایین فاکتور چاپ می‌شود — مثلا تحویل درب منزل</li>
<li><b>ثبت و پرداخت:</b> دکمه بزرگ سبز تمام عرض «ثبت و پرداخت» — بعد از ثبت، فاکتور چاپی باز می‌شود و سبد خالی می‌شود و آماده مشتری بعدی است</li>
</ol>
