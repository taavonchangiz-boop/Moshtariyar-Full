<div class="card" id="m14"><h2>۱۴. گزارشات نه بخشی — چطور هر گزارش را ببینیم</h2>
<p>مسیر: <span class="kbd">گزارش‌ها</span> — <span class="kbd">/app/reports</span> — تب‌ها: نمای کلی، گزارش فروش، گروه‌بندی رفتار خرید، ارزش طول عمر، درآمد بازگشتی، پرفروش‌ترین‌ها، کانال‌های فروش، پرداخت‌ها، پشتیبانی، خروجی و ارسال</p>
<h3>هر تب چه دارد و چطور ببینی:</h3>
<ul>
<li><b>نمای کلی:</b> روند فروش روزانه/هفتگی/ماهانه با نمودار خطی قابل انتخاب بازه هفت روزه، سی روزه، نود روزه، یک ساله، همه زمان — میانگین سفارش با تومان، وضعیت سفارش‌ها با نوار پیشرفت و درصد</li>
<li><b>گزارش فروش:</b> ساعت‌های طلایی (کدام ساعت بیشتر می‌فروشیم) نمودار میله‌ای بیست و چهار ساعته با برچسب ساعت به فارسی، روزهای هفته شنبه تا جمعه نمودار میله‌ای، منبع فروش (فروشگاه اینترنتی، حضوری، صندوق، سرنخ، تلگرام) با جدول تعداد و مبلغ و سهم نوار پیشرفت</li>
<li><b>گروه‌بندی رفتار خرید:</b> شش دسته قهرمانان، وفادار، مستعد، جدید، در معرض خطر، از دست رفته — هر دسته رنگ، تعداد، درصد، توضیح و پیشنهاد کاری — جدول پیشنهاد اقدام برای هر گروه — جدول پنجاه مشتری برتر بر اساس رفتار خرید با نام و موبایل و گروه و تعداد خرید و تازگی روز پیش و مبلغ</li>
<li><b>ارزش طول عمر پیشرفته:</b> شش کارت: میانگین ارزش دوازده ماه آینده، میانگین ریسک، در معرض خطر، از دست رفته، درآمد پیش‌بینی دوازده ماه، کل مشتری تحلیل شده — نمودار توزیع ریسک میله‌ای سالم تا از دست رفته، جدول بخش‌بندی با تعداد و سهم نوار پیشرفت و دکمه مدیریت بخش‌ها و اجرای بخش‌بندی خودکار، دو جدول پنجاه مشتری برتر پیش‌بینی و بیست ارزشمند در معرض ریزش با ستون نام و موبایل و کل خرید و میانگین سبد و فاصله خرید و ریسک و ارزش پیش‌بینی و دکمه کمپین بازگشت</li>
<li><b>درآمد بازگشتی:</b> شش کارت، نمودار ماهانه یکتا با دو محور، فهرست بازگشت‌های بازه با غیبت روز و مبلغ و تاریخ شمسی و دکمه پرونده، پنج بازگشت برتر</li>
<li><b>پرفروش‌ترین‌ها:</b> بیست محصول پرفروش با رتبه و نام و تعداد و فروش، ده دسته پرفروش، بیست مشتری برتر بازه با نام و موبایل و سفارش و خرید و دکمه پرونده</li>
<li><b>کانال‌های فروش:</b> نمودار دایره‌ای توزیع فروش بر اساس کانال — فروشگاه اینترنتی، حضوری، صندوق، سرنخ و... — جدول کانال با تعداد و فروش و سهم نوار پیشرفت</li>
<li><b>پرداخت‌ها:</b> سه کارت: مجموع پرداخت با تومان، تعداد درگاه فعال، کل تراکنش — جدول عملکرد درگاه‌ها و وضعیت تراکنش‌ها</li>
<li><b>پشتیبانی:</b> چهار کارت: کل تیکت، باز، بسته، میانگین پاسخ به دقیقه، تفکیک تیکت بر اساس بخش با سهم نوار پیشرفت</li>
<li><b>خروجی و ارسال:</b> چهار کارت: گزارش مشتریان برتر پانصد تایی، محصولات پرفروش پانصد تایی، خروجی گروه‌بندی رفتار خرید پنجاه تایی، ارزش طول عمر پنجاه تایی — هر کارت دکمه دانلود فایل صفحه گسترده</li>
</ul>
</div>

